"""Builds the HTML pages from partials/<page>.html and one shared shell.

Run from the repo root: python scripts/build_pages.py
Edit partials/*.html or the shell below, never the generated *.html pages.
"""
import html

PAGES = [
    # id, file, nav label, <title>, description
    ('index', 'index.html', 'Home', 'Breach Clock', 'Cybercrime, counted: attacks in flight, money lost, the biggest breaches and how they happen. Every figure sourced.'),
    ('latest', 'latest.html', 'Latest', 'Latest attacks · Breach Clock', 'The newest notable data breaches and the software flaws attackers are using right now, updated daily.'),
    ('live', 'live.html', 'Live', 'Attacks in flight · Breach Clock', 'DDoS attacks travelling between countries at the real average pace, from Cloudflare data.'),
    ('clock', 'clock.html', 'Since you arrived', 'The meter is running · Breach Clock', 'Money lost, data exposed and phishing sites created since you opened the page, at published rates.'),
    ('named', 'named.html', 'On the record', 'On the record · Breach Clock', 'Cyberattacks researchers or governments traced to a country, 2000 to 2025, from EuRepoC.'),
    ('scale', 'scale.html', 'Scale', 'Breaches to scale · Breach Clock', 'The biggest data breaches drawn to scale, one dot per million records.'),
    ('how', 'how.html', 'How it happens', 'How it happens · Breach Clock', 'Five common attacks, step by step, and the one place each could have been stopped.'),
    ('sources', 'sources.html', 'Sources', 'Sources · Breach Clock', 'Every figure on Breach Clock and the report it came from.'),
    ('about', 'about.html', 'About', 'About · Breach Clock', 'What Breach Clock shows and how to read its numbers.'),
]
NAV = ('latest', 'about', 'sources')  # the rest are reached from the home cards
ICON = "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Ccircle cx='16' cy='16' r='13' fill='none' stroke='%23ffb000' stroke-width='3'/%3E%3Cpath d='M16 8v8l5 3' stroke='%23ffb000' stroke-width='3' fill='none' stroke-linecap='round'/%3E%3C/svg%3E"


def shell(pid, title, desc, body):
    nav = '\n'.join(
        f'      <a href="{f}"{" aria-current=\"page\"" if p == pid else ""}>{label}</a>'
        for p, f, label, _, _ in PAGES if p in NAV
    )
    pill = '' if pid in ('clock', 'index') else '''
  <a class="float-live" id="floatLive" href="clock.html" aria-label="Lost since you opened this page. Open the live counters.">
    <span class="live-dot" aria-hidden="true"></span>
    <span class="fl-num" id="floatNum">$0</span>
    <span class="fl-label">lost to reported internet crime since you opened this page</span>
  </a>
'''
    return f'''<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{html.escape(title)}</title>
  <meta name="description" content="{html.escape(desc)}">
  <meta name="theme-color" content="#0d0c0b">
  <link rel="icon" href="{ICON}">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=Space+Grotesk:wght@400;500;600;700&display=swap" rel="stylesheet">
  <link rel="stylesheet" href="styles.css">
  <script>try{{var t=localStorage.getItem('breachclock:theme');if(t)document.documentElement.dataset.theme=t}}catch(e){{}}</script>
</head>
<body data-page="{pid}">
  <!-- Generated by scripts/build_pages.py from partials/{pid}.html. Edit those, not this file. -->
  <div class="deck">
    <header class="card bar">
      <a class="brand" href="index.html" aria-label="Breach Clock, home">
        <svg viewBox="0 0 32 32" aria-hidden="true"><circle cx="16" cy="16" r="13"/><path d="M16 8v8l5 3"/></svg>
        Breach Clock
      </a>
      <nav class="nav" aria-label="Pages">
{nav}
      </nav>
      <button class="icon-btn" id="themeBtn" type="button" aria-label="Switch light or dark theme" title="Switch theme">
        <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 3a9 9 0 1 0 9 9 7 7 0 0 1-9-9z"/></svg>
      </button>
    </header>

    <main class="deck-main">
{body}    </main>

    <footer class="card foot">
      <p>Breach Clock. Figures refresh as new reports come out. A static site; nothing about you is tracked.</p>
      <span class="foot-links"><a href="about.html">About</a> <a href="sources.html">Sources</a> <a href="https://github.com/rohanpaldesign/breach-clock">GitHub</a></span>
    </footer>
  </div>
{pill}
  <dialog class="src-dialog" id="srcDialog" aria-labelledby="srcDialogTitle">
    <form method="dialog"><button class="icon-btn close" aria-label="Close"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18"/></svg></button></form>
    <div id="srcDialogBody"></div>
  </dialog>

  <script type="module" src="app.js"></script>
</body>
</html>
'''


for pid, f, _, title, desc in PAGES:
    body = open(f'partials/{pid}.html', encoding='utf-8').read()
    with open(f, 'w', encoding='utf-8', newline='\n') as out:
        out.write(shell(pid, title, desc, body))
    print('wrote', f)
